-- 1. Create Users Table
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    password TEXT NOT NULL,
    phone VARCHAR(20),
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Login Sessions / Logs Table
CREATE TABLE IF NOT EXISTS public.login_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    mac_address VARCHAR(17),
    ip_address VARCHAR(45),
    login_time TIMESTAMPTZ DEFAULT NOW(),
    logout_time TIMESTAMPTZ NULL,
    data_used BIGINT DEFAULT 0,
    is_active BOOLEAN DEFAULT TRUE
);

-- 3. Create Vouchers / Access Codes Table
CREATE TABLE IF NOT EXISTS public.vouchers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) UNIQUE NOT NULL,
    duration_minutes INT NOT NULL,
    data_limit BIGINT DEFAULT NULL,
    is_used BOOLEAN DEFAULT FALSE,
    used_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    used_at TIMESTAMPTZ NULL
);

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.login_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vouchers ENABLE ROW LEVEL SECURITY;

-- Safely recreate access policies
DROP POLICY IF EXISTS "Allow full access to users" ON public.users;
CREATE POLICY "Allow full access to users" ON public.users
    FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow full access to login_sessions" ON public.login_sessions;
CREATE POLICY "Allow full access to login_sessions" ON public.login_sessions
    FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow full access to vouchers" ON public.vouchers;
CREATE POLICY "Allow full access to vouchers" ON public.vouchers
    FOR ALL USING (true) WITH CHECK (true);

-- 5. Supabase Storage Bucket for Captive Portal Media / Assets
INSERT INTO storage.buckets (id, name, public) 
VALUES ('portal-assets', 'portal-assets', true)
ON CONFLICT (id) DO NOTHING;

DROP POLICY IF EXISTS "Public Access for Portal Assets" ON storage.objects;
CREATE POLICY "Public Access for Portal Assets" ON storage.objects
    FOR SELECT USING (bucket_id = 'portal-assets');

DROP POLICY IF EXISTS "Allow uploads to Portal Assets" ON storage.objects;
CREATE POLICY "Allow uploads to Portal Assets" ON storage.objects
    FOR INSERT WITH CHECK (bucket_id = 'portal-assets');
